    // Пять примеров подряд. Верный вариант БОЛЬШЕ НЕ ПЕРВЫЙ: с 26 августа
    // порядок перемешивается прибором (баг-репорт, баг 4). Перебираем
    // варианты, пока не откроется решение — ровно так же, как это делает
