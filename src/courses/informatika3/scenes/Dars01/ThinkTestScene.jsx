// ============================================================================
// informatika3/scenes/Dars01/ThinkTestScene.jsx — ПРОВЕРКА «КОМПЬЮТЕР ДУМАЕТ?»
//
// Экран снимает ложную модель, которая у десятилетнего уже есть: «компьютер
// умный, он сам догадается». Пока она держится, вся дальнейшая информатика
// читается неправильно — от «программа» до «ошибка в программе».
//
// Механика — предсказание, поэтому экран обслуживает HookScreen, а тот передаёт
// сцене ровно один проп: gathered (ответил ребёнок или ещё нет). До ответа
// результаты закрыты знаком вопроса: команды видны, а что из них получится —
// ребёнок должен предположить сам, иначе предсказывать нечего.
//
// Обе команды правильные с точки зрения компьютера, и это суть: во второй строке
// ошибся ЧЕЛОВЕК, а компьютер честно сделал написанное. «Компьютер ошибся» и
// «компьютер сделал не то, что я хотел» — разные вещи, и различить их надо здесь.
//
// Строки и заголовки приходят из content/Dars01.data.js (THINK_ROWS): сцена не
// хранит ни одной фразы.
// ============================================================================

import { CommandBoard, T, useT } from '../../kit/index.js';

const HIDDEN = { uz: '?', ru: '?', en: '?' };

export default function ThinkTestScene({ rows = [], headers = {}, note = null, gathered = false }) {
  const t = useT();
  // До ответа результат закрыт, и пометка bad снята: жёлтая рамка сама выдала бы,
  // в какой строке подвох.
  const shownRows = gathered ? rows : rows.map((r) => ({ cmd: r.cmd, out: HIDDEN, bad: false }));
  return (
    <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 10, width: '100%' }}>
      <CommandBoard headers={headers} rows={shownRows}/>
      {gathered && note && (
        <p
          style={{
            margin: 0, textAlign: 'center', fontWeight: 700, color: T.ink2,
            fontSize: 'clamp(12px, 1.8vw, 15px)', maxWidth: 460,
          }}
        >
          {t(note)}
        </p>
      )}
    </div>
  );
}
